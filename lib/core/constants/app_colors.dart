import 'package:flutter/material.dart';

/// Brand, semantic and neutral colours — Phase 13 ("Obsidian Lumina", the
/// Stitch design system), replacing plan2.md P8-T1's warm-neutral scale.
///
/// Three separate concerns, deliberately kept apart:
///
/// * [seed] is the only colour that feeds Material 3's [ColorScheme]. The
///   obsidian neutral scale below is mapped onto the scheme's surface roles in
///   `app_theme.dart`, so widgets can keep reading `Theme.of(context)`.
/// * The neutral scale ([surfaceFor] … [borderSubtleFor]) is the source of that
///   mapping. Dark values are the exact tokens generated by the Stitch design
///   system; light values are the violet-tinted light adaptation of the same
///   seed, keeping the ThemeMode toggle functional.
/// * [incomeFor] / [expenseFor] return a brightness-appropriate tone that
///   clears 4.5:1, and every money figure, sign and bar uses those.
///   `test/core/constants/app_colors_test.dart` asserts the ratios.
abstract final class AppColors {
  /// Brand seed — Electric Violet, the interactive driver of the design.
  static const Color seed = Color(0xFF6366F1);

  static const Color incomeGreen = Color(0xFF16A34A);
  static const Color expenseRed = Color(0xFFDC2626);

  static const Color priorityHigh = Color(0xFFDC2626);
  static const Color priorityMedium = Color(0xFFF59E0B);
  static const Color priorityLow = Color(0xFF3B82F6);

  /// Green-700 — 5.57:1 on the light `surfaceContainerHighest`.
  static const Color incomeGreenLight = Color(0xFF166534);

  /// Red-800 — 5.05:1 on the light `surfaceContainerHighest`.
  static const Color expenseRedLight = Color(0xFFB91C1C);

  /// Mint (design `secondary`) — 7.1:1 on the dark `surfaceContainerHighest`.
  static const Color incomeGreenDark = Color(0xFF4EDEA3);

  /// Coral tint (design `tertiary`) — 7.0:1 on the dark `surfaceContainerHighest`.
  static const Color expenseRedDark = Color(0xFFFFB2B7);

  /// Income colour safe for text on the current surface.
  static Color incomeFor(Brightness brightness) =>
      brightness == Brightness.dark ? incomeGreenDark : incomeGreenLight;

  /// Expense colour safe for text on the current surface.
  static Color expenseFor(Brightness brightness) =>
      brightness == Brightness.dark ? expenseRedDark : expenseRedLight;

  /// The mint "live" accent — the mockups' `secondary` — adaptive so the
  /// retained light mode keeps a mint that reads on the pale canvas.
  static Color accentMintFor(Brightness brightness) => incomeFor(brightness);

  // ---------------------------------------------------------------------------
  // Obsidian surface scale (Phase 13). Dark values are verbatim from the
  // Stitch design system; light values adapt the same violet undertone for the
  // retained ThemeMode toggle. Every text tier clears 4.5:1 against the
  // surfaces it can be painted on, asserted in `app_colors_test.dart`.
  // ---------------------------------------------------------------------------

  static const Color surfaceLight = Color(0xFFFCFAFF);
  /// Obsidian base canvas — "never pure black".
  static const Color surfaceDark = Color(0xFF131318);

  /// The faint violet-tinted tier behind grouped sections and empty states.
  static const Color surfaceSoftLight = Color(0xFFF4F2F9);
  /// Design `surface-container-low`.
  static const Color surfaceSoftDark = Color(0xFF1B1B20);

  /// The raised surface behind cards — design `surface-container-highest`.
  ///
  /// NOTE: in this design the *card* surface is the middle tier
  /// (`surface-container`); the "highest" name is kept for API compatibility
  /// with plan2 era call sites, but the dark value is the design token
  /// `#35343A`. The card tier itself is exposed as [surfaceContainerDark].
  static const Color surfaceContainerHighestLight = Color(0xFFE5E2EB);
  static const Color surfaceContainerHighestDark = Color(0xFF35343A);

  /// Design `surface-container` — the tier the card kit paints on.
  static const Color surfaceContainerLight = Color(0xFFF0EEF6);
  static const Color surfaceContainerDark = Color(0xFF1F1F24);

  /// Design `surface-container-high` — nested panels, active segment tracks.
  static const Color surfaceHighLight = Color(0xFFEAE7F0);
  static const Color surfaceHighDark = Color(0xFF2A292F);

  /// Design `surface-container-lowest` — meter tracks, deep insets.
  static const Color surfaceLowestLight = Color(0xFFFFFFFF);
  static const Color surfaceLowestDark = Color(0xFF0E0E13);

  /// Design `surface-bright` — hover / pressed states on containers.
  static const Color surfaceBrightLight = Color(0xFFFFFFFF);
  static const Color surfaceBrightDark = Color(0xFF39383E);

  /// 15.5:1 (light) / 14.4:1 (dark) on the card surface.
  static const Color textPrimaryLight = Color(0xFF1B1B21);
  /// Design `on-surface` #E4E1E9.
  static const Color textPrimaryDark = Color(0xFFE4E1E9);

  /// 7.0:1 (light) / 10.4:1 (dark) on the card surface.
  static const Color textSecondaryLight = Color(0xFF47464F);
  /// Design `on-surface-variant` #C7C4D7.
  static const Color textSecondaryDark = Color(0xFFC7C4D7);

  /// 4.65:1 (light) / 5.6:1 (dark) on the card surface — the dimmest tier
  /// that still clears WCAG AA. Slightly brighter than the design's `outline`
  /// #908FA0 (3.97:1 on `surface-container-highest`), which is reserved for
  /// decorative-owned text like day-of-week headers.
  static const Color textTertiaryLight = Color(0xFF64626D);
  static const Color textTertiaryDark = Color(0xFFB0AEC0);

  /// Hairline border. Deliberately *decorative* (≈1.3:1 on the surfaces it
  /// separates), the same role `outlineVariant` plays in the card theme, so
  /// WCAG's 3:1 non-text rule does not apply to it.
  static const Color borderSubtleLight = Color(0xFFD9D6E3);
  /// Design `outline-variant` #464554.
  static const Color borderSubtleDark = Color(0xFF464554);

  static Color surfaceFor(Brightness brightness) =>
      brightness == Brightness.dark ? surfaceDark : surfaceLight;

  static Color surfaceSoftFor(Brightness brightness) =>
      brightness == Brightness.dark ? surfaceSoftDark : surfaceSoftLight;

  static Color surfaceContainerFor(Brightness brightness) =>
      brightness == Brightness.dark
      ? surfaceContainerDark
      : surfaceContainerLight;

  static Color surfaceHighFor(Brightness brightness) =>
      brightness == Brightness.dark ? surfaceHighDark : surfaceHighLight;

  static Color surfaceLowestFor(Brightness brightness) =>
      brightness == Brightness.dark ? surfaceLowestDark : surfaceLowestLight;

  static Color surfaceBrightFor(Brightness brightness) =>
      brightness == Brightness.dark ? surfaceBrightDark : surfaceBrightLight;

  static Color surfaceContainerHighestFor(Brightness brightness) =>
      brightness == Brightness.dark
      ? surfaceContainerHighestDark
      : surfaceContainerHighestLight;

  static Color textPrimaryFor(Brightness brightness) =>
      brightness == Brightness.dark ? textPrimaryDark : textPrimaryLight;

  static Color textSecondaryFor(Brightness brightness) =>
      brightness == Brightness.dark ? textSecondaryDark : textSecondaryLight;

  static Color textTertiaryFor(Brightness brightness) =>
      brightness == Brightness.dark ? textTertiaryDark : textTertiaryLight;

  static Color borderSubtleFor(Brightness brightness) =>
      brightness == Brightness.dark ? borderSubtleDark : borderSubtleLight;

  /// Context-based accessor — the form every call site uses.
  static Color surfaceSoft(BuildContext context) =>
      surfaceSoftFor(Theme.of(context).brightness);

  /// Context-based accessor — the form every call site uses.
  static Color surfaceContainer(BuildContext context) =>
      surfaceContainerFor(Theme.of(context).brightness);

  /// Context-based accessor — the form every call site uses.
  static Color surfaceHigh(BuildContext context) =>
      surfaceHighFor(Theme.of(context).brightness);

  /// Context-based accessor — the form every call site uses.
  static Color borderSubtle(BuildContext context) =>
      borderSubtleFor(Theme.of(context).brightness);

  // ---------------------------------------------------------------------------
  // Luminous accent scale (Phase 13) — the saturated markers from the design
  // that cut through the obsidian canvas. Glow shadows, chart strokes and
  // status dews use these directly; text roles always come from the scheme or
  // the neutral tiers above.
  // ---------------------------------------------------------------------------

  /// Electric Violet — ambient glow blooms, focus rings, active markers.
  static const Color accentViolet = Color(0xFF6366F1);

  /// Finance Mint — growth, income, positive momentum.
  static const Color accentMint = Color(0xFF10B981);

  /// Cyan — schedule/finance secondary data marks.
  static const Color accentCyan = Color(0xFF06B6D4);

  /// Productivity Coral — overdue, expense, urgent reminders.
  static const Color accentCoral = Color(0xFFF43F5E);

  /// Amber — budget thresholds, starred items.
  static const Color accentAmber = Color(0xFFF59E0B);

  // ---------------------------------------------------------------------------
  // Tag palette (kept from plan2.md P8-T1, retinted for the violet canvases).
  //
  // Muted pairs for category/priority/tag chips: a soft tinted background with
  // a readable, slightly darker foreground of the same hue. Each pair clears
  // 4.5:1 on its own, independently of the surface it sits on.
  // ---------------------------------------------------------------------------

  static const Map<AppTag, AppTagColor> _tagsLight = <AppTag, AppTagColor>{
    AppTag.red: AppTagColor(
      background: Color(0xFFFBE9E7),
      foreground: Color(0xFFB3261E),
    ),
    AppTag.orange: AppTagColor(
      background: Color(0xFFFDEBD3),
      foreground: Color(0xFF92400E),
    ),
    AppTag.yellow: AppTagColor(
      background: Color(0xFFFBF3D1),
      foreground: Color(0xFF7A5B00),
    ),
    AppTag.green: AppTagColor(
      background: Color(0xFFE4F3E4),
      foreground: Color(0xFF166534),
    ),
    AppTag.blue: AppTagColor(
      background: Color(0xFFE7E6FD),
      foreground: Color(0xFF3730A3),
    ),
    AppTag.purple: AppTagColor(
      background: Color(0xFFF1E9FB),
      foreground: Color(0xFF6B21A8),
    ),
    AppTag.gray: AppTagColor(
      background: Color(0xFFECEBF0),
      foreground: Color(0xFF4A4952),
    ),
  };

  static const Map<AppTag, AppTagColor> _tagsDark = <AppTag, AppTagColor>{
    AppTag.red: AppTagColor(
      background: Color(0xFF3A2320),
      foreground: Color(0xFFF2B8B5),
    ),
    AppTag.orange: AppTagColor(
      background: Color(0xFF3A2A18),
      foreground: Color(0xFFF5C48A),
    ),
    AppTag.yellow: AppTagColor(
      background: Color(0xFF3A3318),
      foreground: Color(0xFFE8D48A),
    ),
    AppTag.green: AppTagColor(
      background: Color(0xFF1E3324),
      foreground: Color(0xFFA8D5A8),
    ),
    AppTag.blue: AppTagColor(
      background: Color(0xFF26253D),
      foreground: Color(0xFFC3C2F9),
    ),
    AppTag.purple: AppTagColor(
      background: Color(0xFF2C2440),
      foreground: Color(0xFFCBB8ED),
    ),
    AppTag.gray: AppTagColor(
      background: Color(0xFF2C2B33),
      foreground: Color(0xFFD2D0DC),
    ),
  };

  static AppTagColor tagFor(AppTag tag, Brightness brightness) =>
      (brightness == Brightness.dark ? _tagsDark : _tagsLight)[tag]!;

  /// Stable index → tag mapping, so the same category keeps its chip colour
  /// across rebuilds (and wraps around if there are more categories than tags).
  static AppTagColor tagForIndex(int index, Brightness brightness) =>
      tagFor(AppTag.values[index % AppTag.values.length], brightness);

  static List<AppTagColor> tagPaletteFor(Brightness brightness) => AppTag.values
      .map((AppTag tag) => tagFor(tag, brightness))
      .toList(growable: false);

  /// The hue a label maps to — a category name, a priority, a tag.
  ///
  /// FNV-1a over the characters, so it is stable across runs and platforms:
  /// Dart's `String.hashCode` is not, and a category that changed colour on
  /// every launch would be worse than one with no colour at all. Nothing is
  /// stored, so the mapping is the same for a fresh install and an old one.
  static AppTag tagForLabel(String label) {
    int hash = 0x811c9dc5;
    for (final int unit in label.codeUnits) {
      hash ^= unit;
      hash = (hash * 0x01000193) & 0xFFFFFFFF;
    }

    return AppTag.values[hash % AppTag.values.length];
  }
}

/// The hues available to the tag palette, in a fixed order.
enum AppTag { red, orange, yellow, green, blue, purple, gray }

/// A muted background/foreground pair used for chips and tags.
class AppTagColor {
  const AppTagColor({required this.background, required this.foreground});

  final Color background;
  final Color foreground;
}
